-- Stable author order: rows inserted in one batch share created_at, so a
-- monotonically increasing identity value records the exact insertion order.
ALTER TABLE public.co_authors
  ADD COLUMN IF NOT EXISTS sort_order bigint GENERATED BY DEFAULT AS IDENTITY;

-- Backfill existing rows: creation time first, then the physical insertion order.
WITH ordered AS (
  SELECT id, row_number() OVER (ORDER BY created_at NULLS FIRST, sort_order) AS rn
  FROM public.co_authors
)
UPDATE public.co_authors c SET sort_order = o.rn FROM ordered o WHERE o.id = c.id;

SELECT setval(
  pg_get_serial_sequence('public.co_authors', 'sort_order'),
  GREATEST((SELECT COALESCE(MAX(sort_order), 0) FROM public.co_authors), 1)
);

CREATE INDEX IF NOT EXISTS co_authors_article_sort_idx ON public.co_authors (article_id, sort_order);